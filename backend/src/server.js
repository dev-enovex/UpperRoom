import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import dotenv from 'dotenv';
import rateLimit from 'express-rate-limit';
import connectDB from './config/db.js';
import authRoutes from './routes/authRoutes.js';
import eventRoutes from './routes/eventRoutes.js';
import paymentRoutes from './routes/paymentRoutes.js';
import ticketRoutes from './routes/ticketRoutes.js';
import {paystackWebhook,flutterwaveWebhook} from './controllers/paymentController.js';
dotenv.config();
const app=express();
app.use(helmet());
app.use(cors({origin:process.env.CLIENT_URL||'http://localhost:5173'}));
app.post('/api/payments/paystack/webhook',express.json({verify:(req,res,buf)=>{req.rawBody=buf;}}),paystackWebhook);
app.post('/api/payments/flutterwave/webhook',express.json(),flutterwaveWebhook);
app.use(express.json({limit:'1mb'}));
app.use('/api',rateLimit({windowMs:15*60*1000,limit:250,standardHeaders:true,legacyHeaders:false}));
app.get('/api/health',(req,res)=>res.json({success:true,service:'UpperRoom Soar Summit API'}));
app.use('/api/auth',authRoutes);app.use('/api/events',eventRoutes);app.use('/api/payments',paymentRoutes);app.use('/api/tickets',ticketRoutes);
app.use((err,req,res,next)=>{console.error(err);res.status(500).json({message:'Unexpected server error.'});});
const port=process.env.PORT||5000;
connectDB().then(()=>app.listen(port,()=>console.log(`UpperRoom API listening on ${port}`))).catch(e=>{console.error('Database connection failed:',e.message);process.exit(1);});
